    async def chat_completion(
        self,
        messages: List[Message],
        model_type: Any,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
        stream: bool = False,
        tools: Optional[List[Dict[str, Any]]] = None,
    ) -> ChatResponse:
        """Send chat completion request to OpenRouter."""
        if isinstance(model_type, ModelType):
            model_id = self.model_ids[model_type]
        else:
            raw_str = str(model_type).strip()
            known_providers = ["google", "gemini", "deepseek", "qwen", "anthropic", "claude", "openai", "groq", "mistral", "openrouter"]
            if ":" in raw_str:
                parts = raw_str.split(":", 1)
                prov = parts[0].lower().strip()
                if "/" not in parts[0] and prov in known_providers:
                    mid = parts[1]
                    if prov == "openrouter":
                        model_id = mid
                    elif prov in ["google", "gemini"]:
                        model_id = f"google/{mid}" if not mid.startswith("google/") else mid
                    elif prov == "deepseek":
                        model_id = f"deepseek/{mid}" if not mid.startswith("deepseek/") else mid
                    elif prov == "qwen":
                        model_id = f"qwen/{mid}" if not mid.startswith("qwen/") else mid
                    elif prov in ["anthropic", "claude"]:
                        model_id = f"anthropic/{mid}" if not mid.startswith("anthropic/") else mid
                    elif prov == "openai":
                        model_id = f"openai/{mid}" if not mid.startswith("openai/") else mid
                    elif prov in ["mistral"]:
                        model_id = f"mistralai/{mid}" if not mid.startswith("mistralai/") else mid
                    else:
                        model_id = mid
                else:
                    model_id = raw_str
            else:
                model_id = raw_str.replace("openrouter/", "")
                
            model_lower = model_id.lower()
            if "gemini" in model_lower and not model_lower.startswith("google/"):
                model_id = f"google/{model_id}"
            elif "deepseek" in model_lower and not model_lower.startswith("deepseek/"):
                model_id = f"deepseek/{model_id}"
            elif "qwen" in model_lower and not model_lower.startswith("qwen/"):
                model_id = f"qwen/{model_id}"
            elif "claude" in model_lower and not model_lower.startswith("anthropic/"):
                model_id = f"anthropic/{model_id}"
            elif ("mistral" in model_lower or "codestral" in model_lower) and not model_lower.startswith("mistralai/"):
                model_id = f"mistralai/{model_id}"
            
        # Use defaults if not provided
        if temperature is None:
            temperature = config.settings.temperature
        if max_tokens is None:
            caps = self.model_capabilities.get(model_type) if isinstance(model_type, ModelType) else None
            max_tokens = min(config.settings.max_tokens_per_request, caps.max_tokens if caps else 128000)
            
        provider = None
        if "deepseek" in model_id.lower():
            provider = {"parameters": {"reasoning_effort": "max"}}
        
        request = ChatRequest(
            model=model_id,
            messages=messages,
            temperature=temperature,
            max_tokens=max_tokens,
            stream=stream,
            tools=tools,
            tool_choice="auto" if tools else None,
            provider=provider,
        )
        
        max_retries = 2
        for attempt in range(max_retries + 1):
            try:
                from datetime import datetime
                current_time = datetime.now().strftime("%H:%M:%S")
                print(f"[{current_time}] 🤖 Requesting completion from model: {model_id} (Attempt {attempt+1}/{max_retries+1})...")
                response = await self.client.post(
                    f"{self.base_url}/chat/completions",
                    json=request.dict(exclude_none=True),
                )
                
                # Check for rate limiting
                if response.status_code == 429 and attempt < max_retries:
                    print(f"⚠️ Rate limited (429). Retrying in 2 seconds...")
                    await asyncio.sleep(2)
                    continue
                    
                response.raise_for_status()
                
                data = response.json()
                
                # Track cost
                if data.get("usage"):
                    usage = data["usage"]
                    input_tokens = usage.get("prompt_tokens", 0)
                    output_tokens = usage.get("completion_tokens", 0)
                    from datetime import datetime
                    current_time = datetime.now().strftime("%H:%M:%S")
                    print(f"[{current_time}] ✅ Response received from {model_id} (Tokens: {input_tokens} in, {output_tokens} out)")
                    config.track_cost(model_id, input_tokens, output_tokens)
                
                return ChatResponse(**data)
                
            except httpx.HTTPStatusError as e:
                print(f"HTTP error: {e.response.status_code} - {e.response.text}")
                if attempt == max_retries:
                    raise
            except Exception as e:
                print(f"Error in chat completion: {e}")
                if attempt == max_retries:
                    raise
    
    async def chat_completion_stream(
        self,
        messages: List[Message],
        model_type: ModelType,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        """Stream chat completion response."""
        model_id = self.model_ids[model_type]
        
        if temperature is None:
            temperature = config.settings.temperature
        if max_tokens is None:
            max_tokens = min(
                config.settings.max_tokens_per_request,
                self.model_capabilities[model_type].max_tokens
            )
            
        provider = None
        if "deepseek" in model_id.lower():
            provider = {"parameters": {"reasoning_effort": "max"}}
        
        request = ChatRequest(
            model=model_id,
            messages=messages,
            temperature=temperature,
            max_tokens=max_tokens,
            stream=True,
            provider=provider,
        )
        
        try:
            async with self.client.stream(
                "POST",
                f"{self.base_url}/chat/completions",
                json=request.dict(exclude_none=True),
                timeout=120.0,
            ) as response:
                response.raise_for_status()
                
                collected_content = []
                async for line in response.aiter_lines():
                    if line.startswith("data: "):
                        data = line[6:]
                        if data == "[DONE]":
                            break
                        
                        try:
                            chunk = json.loads(data)
                            if "choices" in chunk and chunk["choices"]:
                                delta = chunk["choices"][0].get("delta", {})
                                if "content" in delta and delta["content"]:
                                    content = delta["content"]
                                    collected_content.append(content)
                                    yield content
                        except json.JSONDecodeError:
                            continue
            
            # Track cost (approximate)
            if self.tokenizer and collected_content:
                full_response = "".join(collected_content)
                output_tokens = len(self.tokenizer.encode(full_response))
                # Estimate input tokens
                input_messages = "\n".join([m.content for m in messages])
                input_tokens = len(self.tokenizer.encode(input_messages))
                config.track_cost(model_id, input_tokens, output_tokens)
                
        except Exception as e:
            print(f"Error in streaming: {e}")
            raise
    
    def estimate_tokens(self, text: str) -> int:
        """Estimate token count for text."""
        if self.tokenizer:
            return len(self.tokenizer.encode(text))
        # Fallback: approximate 4 chars per token
        return len(text) // 4
    
    def get_model_capabilities(self, model_type: ModelType) -> ModelCapabilities:
        """Get capabilities for a model."""
        return self.model_capabilities[model_type]
    
    def get_available_models(self) -> List[Dict[str, Any]]:
        """Get list of available models with capabilities."""
        models = []
        for model_type, model_id in self.model_ids.items():
            caps = self.model_capabilities[model_type]
            models.append({
                "type": model_type.value,
                "id": model_id,
                "capabilities": {
                    "max_tokens": caps.max_tokens,
                    "supports_tools": caps.supports_tools,
                    "supports_vision": caps.supports_vision,
                    "reasoning_strength": caps.reasoning_strength,
                    "coding_strength": caps.coding_strength,
                    "speed": caps.speed,
                    "cost_per_token": caps.cost_per_token,
                }
            })
        return models
    
