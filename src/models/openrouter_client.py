def extract_text_content(content: Any) -> str:
    """Extract string content safely from str, list (e.g. thinking/vision blocks), or dict."""
    if content is None:
        return ""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for item in content:
            if isinstance(item, str):
                parts.append(item)
            elif isinstance(item, dict):
                if "text" in item and item["text"]:
                    parts.append(str(item["text"]))
                elif "thinking" in item and item["thinking"]:
                    parts.append(str(item["thinking"]))
                elif item.get("type") == "text" and "text" in item:
                    parts.append(str(item["text"]))
        return "\n".join(parts) if parts else str(content)
    if isinstance(content, dict):
        return content.get("text") or content.get("content") or str(content)
    return str(content)


class ModelType(Enum):
    """Available model types."""
    QWEN = "qwen"
    GEMINI_FLASH = "gemini_flash"
    MIMO = "mimo"
    DEEPSEEK = "deepseek"


class Message(BaseModel):
    """Chat message."""
    role: str = Field(..., description="Message role (system, user, assistant, tool)")
    content: Optional[Union[str, List[Any], Dict[str, Any]]] = Field(default=None, description="Message content")
    tool_calls: Optional[List[Dict[str, Any]]] = Field(default=None, description="Tool calls generated by the model")
    tool_call_id: Optional[str] = Field(default=None, description="Tool call ID for tool responses")
    name: Optional[str] = Field(default=None, description="Name of the tool for tool responses")


class ChatRequest(BaseModel):
    """Chat completion request."""
    model: str = Field(..., description="Model ID")
    messages: List[Message] = Field(..., description="Chat messages")
    temperature: float = Field(default=0.7, ge=0.0, le=2.0, description="Temperature")
    max_tokens: Optional[int] = Field(default=None, description="Maximum tokens to generate")
    stream: bool = Field(default=False, description="Whether to stream response")
    tools: Optional[List[Dict[str, Any]]] = Field(default=None, description="Available tools in OpenAI schema")
    tool_choice: Optional[str] = Field(default=None, description="Tool choice mode (e.g., 'auto')")
    provider: Optional[Dict[str, Any]] = Field(default=None, description="Provider-specific parameters")


class UsageDetails(BaseModel):
    """Usage details from OpenRouter."""
    prompt_tokens: int = Field(..., description="Prompt tokens")
    completion_tokens: int = Field(..., description="Completion tokens")
    total_tokens: int = Field(..., description="Total tokens")
    cost: float = Field(..., description="Cost in USD")
    is_byok: bool = Field(default=False, description="Is BYOK (Bring Your Own Key)")
    prompt_tokens_details: Optional[Dict[str, int]] = Field(default=None, description="Prompt token details")
    cost_details: Optional[Dict[str, float]] = Field(default=None, description="Cost details")
    completion_tokens_details: Optional[Dict[str, int]] = Field(default=None, description="Completion token details")


class ChatResponse(BaseModel):
    """Chat completion response."""
    id: Optional[str] = Field(default=None, description="Response ID")
    object: Optional[str] = Field(default=None, description="Object type")
    created: Optional[int] = Field(default=None, description="Creation timestamp")
    model: Optional[str] = Field(default=None, description="Model used")
    provider: Optional[str] = Field(default=None, description="Model provider")
    system_fingerprint: Optional[str] = Field(default=None, description="System fingerprint")
    choices: Optional[List[Dict[str, Any]]] = Field(default=None, description="Response choices")
    usage: Optional[UsageDetails] = Field(default=None, description="Token usage")
    error: Optional[Dict[str, Any]] = Field(default=None, description="Error returned by API")


